"""Publish the derived inputs the live pipeline needs as a GitHub Release.

Issue #4: a fresh GitHub Actions runner has the code and nothing else. The raw
archive is already a Release (`sackmann-archive`, publish_archive_release.py).
This publishes the second half: the artefacts under tune_scratch/ that
simulate_usopen_live.py reads and that take hours to regenerate.

  elo_raw_ratings_full.parquet          full-archive Elo replay (66 MB)
  set_elo_raw_ratings_full.parquet      set-level Elo (35 MB)
  game_elo_raw_ratings_full.parquet     game-level Elo (35 MB)
  diag_layoff.parquet                   inter-tournament layoff table (10 MB)
  xgb_features_v10_holdout.parquet      only read if the model cache is missing
  xgb_bagged_model_cache_v2_setgame.zip the shipped 5-seed bag + cat_levels
  us_open_2026_predictions.json         the locked pre-tournament forecast,
                                        read by build_blog_data.py

NOT published: prepared_matches_cache.pkl (266 MB, rebuilt from the archive in
~20 s and invalidated by mtime anyway) and hier_final_state.pkl (training only).

Release-as-data-bus rule from C:\\dev\\CLAUDE.md: a release can move ahead of
the code that reads it. The tag carries a vintage date; the workflow pins it.
Re-running with the same tag uploads with --clobber, so an updated Elo replay
replaces the asset in place and the tag's createdAt stops meaning anything -
check asset updatedAt, per the GitHub Release date gotcha.

Usage: python publish_model_inputs_release.py [--tag model-inputs-2026-09]
"""
from __future__ import annotations

import argparse
import hashlib
import shutil
import subprocess
import sys
import zipfile
from pathlib import Path

DD = Path(r"C:\dev\dropshotverse\dropshotdata")
SCRATCH = DD / "tune_scratch"
STAGE = DD / "_release_stage_inputs"
REPO = "peteowen1/dropshotverse"
DEFAULT_TAG = "model-inputs-2026-09"

FILES = ["elo_raw_ratings_full.parquet", "set_elo_raw_ratings_full.parquet",
         "game_elo_raw_ratings_full.parquet", "diag_layoff.parquet",
         "xgb_features_v10_holdout.parquet", "us_open_2026_predictions.json"]
MODEL_DIR = SCRATCH / "xgb_bagged_model_cache_v2_setgame"
MODEL_ZIP = "xgb_bagged_model_cache_v2_setgame.zip"


def log(m: str) -> None:
    print(m, flush=True)


def sha256(p: Path) -> str:
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--tag", default=DEFAULT_TAG)
    args = ap.parse_args()

    gh = shutil.which("gh")
    if not gh:
        raise SystemExit("gh not found on PATH")

    missing = [f for f in FILES if not (SCRATCH / f).exists()]
    if not MODEL_DIR.exists():
        missing.append(MODEL_DIR.name + "/")
    if missing:
        raise SystemExit(f"inputs missing under {SCRATCH}: {missing}")

    STAGE.mkdir(parents=True, exist_ok=True)
    staged: list[Path] = []
    for f in FILES:
        dst = STAGE / f
        shutil.copy2(SCRATCH / f, dst)
        staged.append(dst)

    zpath = STAGE / MODEL_ZIP
    members = sorted(MODEL_DIR.iterdir())
    expected = {"cat_levels.pkl"} | {f"seed{i}.json" for i in range(5)}
    got = {m.name for m in members}
    if got != expected:
        raise SystemExit(f"model cache dir has {sorted(got)}, expected {sorted(expected)}")
    with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED) as z:
        for m in members:
            z.write(m, arcname=f"{MODEL_DIR.name}/{m.name}")
    staged.append(zpath)

    lines = ["| asset | bytes | sha256 |", "|---|---:|---|"]
    for p in staged:
        lines.append(f"| `{p.name}` | {p.stat().st_size:,} | `{sha256(p)}` |")
        log(f"  {p.name:<42} {p.stat().st_size/1048576:8.1f} MB")
    notes = ("Derived inputs for `simulate_usopen_live.py` and `build_blog_data.py` "
             "(issue #4). Regenerated by the Elo replay and `train_best_model.py`; "
             "see `publish_model_inputs_release.py` for what is and is not here.\n\n"
             + "\n".join(lines))
    (STAGE / "notes.md").write_text(notes, encoding="utf-8")

    exists = subprocess.run([gh, "release", "view", args.tag, "--repo", REPO],
                            capture_output=True, text=True).returncode == 0
    if exists:
        log(f"\nrelease {args.tag} exists - uploading with --clobber")
        cmd = [gh, "release", "upload", args.tag, *map(str, staged), "--repo", REPO, "--clobber"]
    else:
        log(f"\ncreating release {args.tag}")
        cmd = [gh, "release", "create", args.tag, *map(str, staged), "--repo", REPO,
               "--title", f"Model inputs ({args.tag})", "--notes-file", str(STAGE / "notes.md")]
    try:
        r = subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8",
                           errors="replace", timeout=30 * 60)
    except subprocess.TimeoutExpired:
        raise SystemExit("gh did not finish in 30 minutes")
    if r.returncode != 0:
        log(r.stdout)
        log(r.stderr)
        raise SystemExit("release publish failed")
    log(r.stdout.strip())
    if exists:
        subprocess.run([gh, "release", "edit", args.tag, "--repo", REPO,
                        "--notes-file", str(STAGE / "notes.md")], check=False)
    log("done")


if __name__ == "__main__":
    sys.exit(main())
