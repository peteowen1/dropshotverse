def load_field(entrants_path: str, tour: str) -> dict:
    with open(entrants_path, encoding="utf-8") as f:
        entrants = json.load(f)
    field_uids, seed_map, names = [], {}, {}
    for e in entrants:
        uid = e["uid"] or f"{tour}:NEW_{e['name'].replace(' ', '_')}"   # synthetic uid for the 1 truly-new player
        field_uids.append(uid)
        names[uid] = e["name"]
        if e["seed"].isdigit():
            seed_map[uid] = float(e["seed"])
    field_uids = sorted(set(field_uids))
    field = pd.DataFrame({"uid": field_uids, "seed": [seed_map.get(u, np.nan) for u in field_uids]})
    top_seed_uid = field.loc[field["seed"] == field["seed"].min(), "uid"].iloc[0] if field["seed"].notna().any() \
        else None
    return {"field_uids": field_uids, "field": field, "seed_map": seed_map, "names": names,
            "top_seed_uid": top_seed_uid}


def run_tour(tour: str, meta: dict, snap: dict, models: list, cat_levels: dict, playstyle_full: pd.DataFrame,
            age_table: pd.DataFrame, n_sims: int) -> dict:
    best_of = 5 if tour == "atp" else 3
    field_uids = meta["field_uids"]
    field = meta["field"]
    names = meta["names"]

    log(f"  [{tour}] {len(field_uids)} entrants, {field['seed'].notna().sum()} seeded")
    h2h = build_h2h_dict(set(field_uids))
    ptab = build_player_table(field_uids, tour, DATE0, SURFACE, snap, playstyle_full, age_table)

    rounds_needed = STAGE_ORDER[:-1]
    round_matrices = build_round_pred_matrices(field_uids, ptab, tour, SURFACE, best_of, "G", h2h, DATE0,
                                                cat_levels, models, rounds_needed)

    idx = {u: k for k, u in enumerate(field_uids)}
    seed = hash(tour + "2026usopen") % 100000
    rng = np.random.default_rng(seed)
    stage_counts = {uid: {s: 0 for s in STAGE_ORDER} for uid in field_uids}
    for _ in range(n_sims):
        bracket = build_random_bracket(field, rng)
        result = simulate_frozen_xgb(bracket, idx, round_matrices, rng)
        for uid, stage in result.items():
            reached_idx = STAGE_ORDER.index(stage)
            for s_idx in range(reached_idx + 1):
                stage_counts[uid][STAGE_ORDER[s_idx]] += 1
    probs = {uid: {s: stage_counts[uid][s] / n_sims for s in STAGE_ORDER} for uid in field_uids}

    # xgb-BT scalar rating too (Pete: "xgb BT if that helps") - same neutral-round
    # round-robin approach as xgb_bt_rating.py, reused via the shared base builder.
    base, pairs_i, pairs_j = build_pairwise_features_base(field_uids, ptab, tour, SURFACE, best_of, "G", h2h, DATE0)
    base["round"] = "R32"
    X = prep_X_d(base, cat_levels)
    dmat = xgb.DMatrix(X, enable_categorical=True)
    preds = np.clip(np.mean([m.predict(dmat) for m in models], axis=0), 1e-9, 1 - 1e-9)
    L = pd.DataFrame({"i": pairs_i, "j": pairs_j, "logit": np.log(preds / (1 - preds))})
    Lp = L.pivot(index="i", columns="j", values="logit").reindex(index=field_uids, columns=field_uids).to_numpy()
    d = (Lp - Lp.T) / 2.0
    np.fill_diagonal(d, 0.0)
    bt_rating = {uid: float(np.nanmean(d[k, :])) for k, uid in enumerate(field_uids)}

    return {"field_uids": field_uids, "names": names, "probs": probs, "bt": bt_rating,
            "seed_map": meta["seed_map"], "top_seed_uid": meta["top_seed_uid"]}


def report(tour_label: str, result: dict, top_n: int = 15) -> None:
    field_uids = result["field_uids"]
    names = result["names"]
    probs = result["probs"]
    bt = result["bt"]

    log(f"\n=== {tour_label}: top {top_n} by simulated P(title) ===")
    p_title = {uid: probs[uid]["W"] for uid in field_uids}
    ranked = sorted(p_title.items(), key=lambda kv: -kv[1])[:top_n]
    for rank, (uid, p) in enumerate(ranked, start=1):
        seed = result["seed_map"].get(uid)
        seed_str = f"(#{int(seed)})" if seed else ""
        row = probs[uid]
        log(f"  {rank:2d}. {names.get(uid, uid):28s} {seed_str:6s} P(title)={p:.3f}  "
            f"P(F)={row['F']:.3f}  P(SF)={row['SF']:.3f}  P(QF)={row['QF']:.3f}")

    log(f"\n  top {top_n} by xgb-BT rating (scalar strength, not tied to this specific draw):")
    ranked_bt = sorted(bt.items(), key=lambda kv: -kv[1])[:top_n]
    for rank, (uid, r) in enumerate(ranked_bt, start=1):
        log(f"  {rank:2d}. {names.get(uid, uid):28s} BT={r:+.3f}")

    if result["top_seed_uid"]:
        rank_of_top_seed = [u for u, _ in sorted(p_title.items(), key=lambda kv: -kv[1])].index(
            result["top_seed_uid"]) + 1
        log(f"\n  anchor: #1 seed ({names.get(result['top_seed_uid'])})'s own simulated title-prob rank: "
            f"{rank_of_top_seed} of {len(field_uids)}")


